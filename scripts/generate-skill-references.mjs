#!/usr/bin/env node
// Generates the GENERATED reference docs for the bpmnkit-claude plugin's skills
// (plugins-claude/bpmnkit-claude/references/). Run after changing the connector
// catalog, FEEL builtins, or the ProcessPlan schema summary in apps/cli.
//
// Usage: node scripts/generate-skill-references.mjs
// Requires: packages/connectors, packages/feel, apps/cli already built (pnpm turbo build).

import { writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..")
const REFS_DIR = join(ROOT, "plugins-claude/bpmnkit-claude/references")

const GENERATED_NOTICE =
	"<!-- GENERATED by scripts/generate-skill-references.mjs — do not hand-edit. -->\n"

// ── references/connectors.md ──────────────────────────────────────────────────

async function generateConnectors() {
	const { listConnectors } = await import(join(ROOT, "packages/connectors/dist/index.js"))
	const all = listConnectors()

	const byDirection = new Map()
	for (const c of all) {
		if (!byDirection.has(c.direction)) byDirection.set(c.direction, [])
		byDirection.get(c.direction).push(c)
	}

	const DIRECTION_LABEL = {
		outbound: "Outbound (service task — call an external system)",
		"inbound-start": "Inbound start (start event — triggered by an external system)",
		"inbound-intermediate": "Inbound intermediate (message catch / receive task)",
		"inbound-boundary": "Inbound boundary (boundary event)",
		agentic: "Agentic (AI Agent Sub-process)",
	}

	const sections = [...byDirection.entries()]
		.sort(([a], [b]) => a.localeCompare(b))
		.map(([direction, connectors]) => {
			const rows = connectors
				.sort((a, b) => a.name.localeCompare(b.name))
				.map((c) => `| \`${c.id}\` | ${c.name} | ${c.taskType ? `\`${c.taskType}\`` : "—"} |`)
				.join("\n")
			return `### ${DIRECTION_LABEL[direction] ?? direction}\n\n| Template id | Name | Task type |\n|---|---|---|\n${rows}`
		})
		.join("\n\n")

	const content = `${GENERATED_NOTICE}
# Connector catalog

${all.length} bundled Camunda 8 out-of-the-box connector templates, from \`@bpmnkit/connectors\`. This is an **index** — look up full input specs at plan-authoring time, don't guess at property keys:

\`\`\`sh
casen connector search "<query>"          # find candidates by name/keyword
casen connector show <template-id>        # required/optional inputs, task type, direction
\`\`\`

## Using a connector in a plan

A \`connector\` step (or an \`aiAgent\` tool's \`connector\` field) references a template by id plus a flat map of input values:

\`\`\`json
{
  "kind": "connector",
  "id": "notify_ops",
  "name": "Notify #ops",
  "connector": {
    "template": "io.camunda.connectors.Slack.v1",
    "values": {
      "method": "chat.postMessage",
      "token": "{{secrets.SLACK_OAUTH_TOKEN}}",
      "data.channel": "#ops",
      "data.text": "=\\"Order \\" + orderId + \\" failed validation\\""
    }
  }
}
\`\`\`

Rules:
- **Value keys** come from \`casen connector show <id>\`'s "Required inputs" / "Optional inputs" lists (dotted paths like \`data.channel\`, not the display label).
- **Secrets**: any input marked \`(secret)\` — API keys, tokens, passwords — must use the \`{{secrets.NAME}}\` placeholder, never a literal credential. \`casen synth\` does not resolve secrets; the target engine (Reebe/Camunda 8) does at runtime from its configured secret store.
- **FEEL values**: a leading \`=\` makes a value a FEEL expression (variables, string concatenation, etc.); without it, the value is a literal string. \`casen synth\`/\`casen lint\` parse-validate every FEEL value — a syntax error surfaces as a plan problem before you ever write BPMN.
- **Conditional fields**: some inputs only apply for a specific dropdown choice (e.g. Slack's \`data.channel\` only applies when \`method\` is \`chat.postMessage\`) — \`casen connector show\` reflects this; supplying a value for a field that doesn't apply is ignored, not an error.
- Direction \`agentic\` connectors (the AI Agent Sub-process) are configured via the \`aiAgent\` plan step, not \`connector\` — see \`references/agentic.md\`.

## Full index

${sections}
`
	writeFileSync(join(REFS_DIR, "connectors.md"), content, "utf-8")
	console.log(`Wrote references/connectors.md (${all.length} connectors)`)
}

// ── references/feel.md ─────────────────────────────────────────────────────────

async function generateFeel() {
	const { builtinNames } = await import(join(ROOT, "packages/feel/dist/builtins.js"))
	const names = builtinNames().sort((a, b) => a.localeCompare(b))
	const columns = names.map((n) => `\`${n}\``).join(", ")

	const content = `${GENERATED_NOTICE}
# FEEL syntax reference

BPMNKit's FEEL implementation (\`@bpmnkit/feel\`) backs every expression \`casen synth\`/\`casen lint\` parse-validates. This is a crib sheet, not the full DMN FEEL spec.

## The "=" convention

Throughout every plan field (connector \`values\`, \`taskHeaders\`, io-mapping \`inputs\`/\`outputs\`, gateway branch \`condition\`, \`aiAgent\` prompts, etc.): a value **starting with \`=\`** is a FEEL expression; a value **without** a leading \`=\` is a literal string. This is a BPMNKit SDK convention layered on top of Zeebe's own \`zeebe:input\`/\`zeebe:output\` source syntax — get it backwards and a literal gets evaluated as FEEL (or vice versa), so double check every value you write.

\`\`\`json
{ "target": "channel", "source": "#ops" }              // literal: the string "#ops"
{ "target": "channel", "source": "=team.slackChannel" } // FEEL: reads process variable team.slackChannel
\`\`\`

## Core syntax

- **Variables / paths**: \`orderId\`, \`order.customer.name\`, \`items[1]\` (1-indexed), \`items[-1]\` (last)
- **String concatenation**: \`"Order " + orderId + " failed"\`
- **Comparisons**: \`amount > 1000\`, \`status = "approved"\`, \`age between 18 and 65\`
- **Boolean logic**: \`and\`, \`or\`, \`not(...)\`
- **Conditionals**: \`if amount > 1000 then "high" else "low"\`
- **Lists**: \`for item in items return item.price\`, \`some item in items satisfies item.price > 100\`, \`every item in items satisfies item.inStock\`
- **Context (object) literals**: \`{ id: toolCall._meta.id, name: toolCall._meta.name }\`
- **Null**: an unbound/undefined variable name evaluates to \`null\`, not an error — a downstream \`ioMapping\` output reading a never-set variable resolves to \`null\` rather than throwing.
- **Temporal literals**: \`@"2024-01-01"\`, \`@"2024-01-01T10:00:00"\`, \`@"P3D"\` (3-day duration)

## Built-in functions (${names.length})

${columns}

Call signature reference for any of these: consult the [DMN 1.3 FEEL spec](https://www.omg.org/spec/DMN/) built-in function tables — BPMNKit's implementation follows the spec's semantics and argument order.

## Common gotchas

- Writing a literal where FEEL was intended (or vice versa) is the single most common plan mistake — when in doubt, run \`casen lint lint --categories feel-syntax <file>.bpmn\` (or let \`casen synth\` surface it — it parse-validates every FEEL-looking value and reports \`steps[N]...\`-scoped problems before compiling).
- FEEL string literals need escaped double quotes inside JSON: \`"=\\"Order \\" + orderId"\`.
- \`fromAi(...)\` (used inside \`aiAgent\` tool parameter mappings) is its own thing layered on FEEL — see \`references/agentic.md\`.
`
	writeFileSync(join(REFS_DIR, "feel.md"), content, "utf-8")
	console.log(`Wrote references/feel.md (${names.length} builtins)`)
}

// ── references/plan-format.md ──────────────────────────────────────────────────

async function generatePlanFormat() {
	const { PLAN_SCHEMA_SUMMARY } = await import(join(ROOT, "apps/cli/dist/commands/plan.js"))

	const content = `${GENERATED_NOTICE}
# ProcessPlan format reference

The \`ProcessPlan\` JSON IR is the **only** thing skills author by hand — never BPMN XML directly. \`casen synth <plan>.json\` compiles it deterministically to laid-out, deployable BPMN.

## Schema summary

\`\`\`
${PLAN_SCHEMA_SUMMARY}
\`\`\`

## Annotated examples

Each example below is a real, tested golden case (\`packages/core/tests/plan.test.ts\`) — copy the shape, not just the idea.

### Linear process (no branching)

\`\`\`json
{
  "version": 1,
  "process": { "id": "order-process", "name": "Order Process" },
  "steps": [
    { "kind": "start", "name": "Order received" },
    { "kind": "serviceTask", "name": "Ship order", "jobType": "shipping:1" },
    { "kind": "end", "name": "Order shipped" }
  ]
}
\`\`\`

### Connector step + error boundary

\`\`\`json
{
  "version": 1,
  "process": { "id": "approval", "name": "Approval Process" },
  "steps": [
    { "kind": "start", "name": "Request submitted" },
    {
      "kind": "gateway",
      "id": "amount_check",
      "name": "Amount > 1000?",
      "gatewayType": "exclusive",
      "branches": [
        {
          "name": "yes",
          "condition": "=amount > 1000",
          "steps": [
            { "kind": "userTask", "id": "manager_review", "name": "Manager review", "candidateGroups": "managers" }
          ]
        },
        { "name": "no", "default": true, "steps": [] }
      ]
    },
    {
      "kind": "serviceTask",
      "id": "process_payment",
      "name": "Process payment",
      "jobType": "payment:1",
      "errorBoundary": {
        "errorCode": "PAYMENT_FAILED",
        "steps": [{ "kind": "end", "id": "payment_failed_end", "errorCode": "PAYMENT_FAILED" }]
      }
    },
    { "kind": "end", "name": "Approved" }
  ]
}
\`\`\`

Both gateway branches converge automatically (an implicit join is inserted when branches don't end in their own \`end\`); the error boundary attaches to \`process_payment\` and its \`errorCode\` must match the code the boundary's \`end\` step re-raises (or that the job type actually throws).

### Message-correlated wait

\`\`\`json
{
  "version": 1,
  "process": { "id": "proc" },
  "steps": [
    { "kind": "start" },
    {
      "kind": "wait",
      "id": "wait_for_payment",
      "name": "Wait for payment",
      "message": { "name": "payment-confirmed", "correlationKey": "=orderId" }
    },
    { "kind": "end" }
  ]
}
\`\`\`

### Multi-instance sub-process

\`\`\`json
{
  "version": 1,
  "process": { "id": "proc" },
  "steps": [
    { "kind": "start" },
    {
      "kind": "subProcess",
      "id": "notify_each",
      "name": "Notify each recipient",
      "steps": [{ "kind": "serviceTask", "id": "send_email", "jobType": "email:1" }],
      "multiInstance": { "collection": "=recipients", "elementVariable": "recipient" },
      "errorBoundary": {
        "errorCode": "NOTIFY_FAILED",
        "steps": [{ "kind": "end", "id": "notify_failed", "errorCode": "NOTIFY_FAILED" }]
      }
    },
    { "kind": "end" }
  ]
}
\`\`\`

For an \`aiAgent\` step example, see \`references/agentic.md\`.

## Workflow

1. Write \`<name>.plan.json\`.
2. \`casen synth <name>.plan.json -o <name>.bpmn\` — if problems are reported, they're keyed by \`path\` (e.g. \`steps[1].branches[0].condition\`); fix the **plan**, never the XML, and re-run. Bound retries to 2 attempts before surfacing the problem to the user.
3. Extending an existing process: \`casen plan extract <name>.bpmn\` to get the current plan back (elements it can't losslessly lift are reported, not guessed at), write a small delta plan with just the new/changed steps, then \`casen synth <delta>.plan.json --merge <name>.bpmn\`.
4. \`plan.tests\` (see schema above) compiles to a \`<name>.bpmn.tests.json\` sidecar automatically — run \`casen test <name>.bpmn\` to execute them.
`
	writeFileSync(join(REFS_DIR, "plan-format.md"), content, "utf-8")
	console.log("Wrote references/plan-format.md")
}

await generateConnectors()
await generateFeel()
await generatePlanFormat()
